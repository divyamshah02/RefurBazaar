class InvoiceView(APIView):
    """
    GET /api/orders/invoice/<order_id>/
    Returns a downloadable PDF invoice for the given order.
    Accessible without authentication (order_id acts as the token).
    """

    def get(self, request, order_id):
        order = get_object_or_404(Order, order_id=order_id)
        pdf_bytes = self._build_pdf(order, request)

        filename = f"Recarvit_Invoice_{order.order_id}.pdf"
        response = HttpResponse(pdf_bytes, content_type="application/pdf")
        response["Content-Disposition"] = f'attachment; filename="{filename}"'
        return response

    # ------------------------------------------------------------------
    # PDF builder
    # ------------------------------------------------------------------

    def _build_pdf(self, order: Order, request) -> bytes:
        buf = BytesIO()
        doc = SimpleDocTemplate(
            buf,
            pagesize=A4,
            leftMargin=MARGIN,
            rightMargin=MARGIN,
            topMargin=MARGIN,
            bottomMargin=MARGIN + 6 * mm,
            title=f"Invoice – {order.order_id}",
            author="Recarvit",
        )

        styles = getSampleStyleSheet()
        story = []

        # ── Header ────────────────────────────────────────────────────
        story += self._header_section(order)
        story.append(Spacer(1, 4 * mm))
        story.append(HRFlowable(width="100%", thickness=1, color=GREEN, spaceAfter=4 * mm))

        # ── Billing & Shipping addresses ──────────────────────────────
        story += self._address_section(order)
        story.append(Spacer(1, 4 * mm))

        # ── Order meta row ────────────────────────────────────────────
        story += self._order_meta(order)
        story.append(Spacer(1, 5 * mm))

        # ── Items table (grouped by refurbisher) ──────────────────────
        story += self._items_section(order, request)
        story.append(Spacer(1, 5 * mm))

        # ── Price summary ─────────────────────────────────────────────
        story += self._price_summary(order)
        story.append(Spacer(1, 6 * mm))

        # ── GST note ──────────────────────────────────────────────────
        note_style = ParagraphStyle(
            "note", parent=styles["Normal"],
            fontSize=7.5, textColor=MID_GRAY,
            leading=11,
        )
        story.append(Paragraph(
            "* All prices are inclusive of applicable GST. This is a computer-generated invoice and does not require a signature.",
            note_style,
        ))
        story.append(Spacer(1, 3 * mm))
        story.append(HRFlowable(width="100%", thickness=0.5, color=LIGHT_GRAY, spaceAfter=3 * mm))
        story.append(Paragraph(
            "Thank you for choosing Recarvit – Certified Refurbished Electronics | recarvit.com",
            ParagraphStyle("thanks", parent=styles["Normal"],
                           fontSize=8, textColor=GREEN, alignment=TA_CENTER, leading=12),
        ))

        doc.build(story, canvasmaker=_NumberedCanvas)
        return buf.getvalue()

