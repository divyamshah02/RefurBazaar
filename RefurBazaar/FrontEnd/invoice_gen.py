def _fmt_inr(value):
    """Format Decimal/float as ₹1,23,456.00"""
    try:
        v = float(value)
    except (TypeError, ValueError):
        return "₹0.00"
    # Indian number formatting
    s = f"{v:,.2f}"
    # Convert Western grouping to Indian grouping
    parts = s.split(".")
    integer = parts[0].replace(",", "")
    dec = parts[1]
    if len(integer) > 3:
        last3 = integer[-3:]
        rest = integer[:-3]
        groups = []
        while len(rest) > 2:
            groups.insert(0, rest[-2:])
            rest = rest[:-2]
        if rest:
            groups.insert(0, rest)
        integer = ",".join(groups) + "," + last3
    return f"₹{integer}.{dec}"


def _logo_path():
    """Return absolute path to the Recarvit logo, trying multiple locations."""
    candidates = [
        os.path.join(settings.BASE_DIR, "static", "images", "new logo", "Recarvit Logo edited-nobg.png"),
        os.path.join(settings.BASE_DIR, "static", "images", "logo.png"),
        os.path.join(os.path.dirname(__file__), "static", "images", "logo.png"),
    ]
    for p in candidates:
        if os.path.exists(p):
            return p
    return None


def _get_company_profile(refurbisher_user):
    """Safely fetch CompanyProfile for a refurbisher."""
    return getattr(refurbisher_user, "company_profile", None)


# ---------------------------------------------------------------------------
# PDF canvas callback – page numbers + border
# ---------------------------------------------------------------------------

class _NumberedCanvas(canvas.Canvas):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_page(total)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def _draw_page(self, total):
        self.saveState()
        # Thin green border
        self.setStrokeColor(GREEN)
        self.setLineWidth(1.2)
        self.rect(MARGIN * 0.6, MARGIN * 0.6,
                  PAGE_W - MARGIN * 1.2, PAGE_H - MARGIN * 1.2)
        # Footer
        self.setFillColor(MID_GRAY)
        self.setFont("Helvetica", 7.5)
        footer = f"Page {self._pageNumber} of {total}  |  Generated by Recarvit – recarvit.com  |  Tax included in item prices"
        self.drawCentredString(PAGE_W / 2, MARGIN * 0.5, footer)
        self.restoreState()


